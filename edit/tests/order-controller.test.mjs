test('simultaneous submit clicks send exactly one POST and keep controls busy until confirmation',async t=>{
  const f=fixture(t),first=f.submit(),doubleClick=f.submit();
  assert.equal(f.controller.isBusy(),true);
  assert.equal(f.node('#send-order').disabled,true);
  const request=await f.waitForRequest(1);assert.equal(request.options.method,'POST');
  assert.equal(f.requests.length,1);f.succeed();await Promise.all([first,doubleClick]);
  assert.equal(f.controller.isBusy(),false);assert.equal(f.form.hidden,true);
  assert.equal(f.node('#order-success').hidden,false);assert.equal(f.navigation.length,1);
});


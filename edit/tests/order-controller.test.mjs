for(const failure of ['quota exception','silent write failure']) {
  test(`receipt storage ${failure} keeps success visible and preserves the request for recovery`,async t=>{
    const f=fixture(t),setItem=f.session.setItem;
    f.session.setItem=(key,value)=>{
      if(key==='ia4tube.edit.receipt.v1') {
        if(failure==='quota exception')throw Object.assign(new Error('Storage full'),{name:'QuotaExceededError'});
        return;
      }
      setItem(key,value);
    };
    const first=f.submit(),original=await f.waitForRequest(1);f.succeed();await first;
    assert.equal(f.node('#order-success').hidden,false);
    assert.equal(f.node('#order-error').hidden,true);
    assert.equal(f.form.hidden,true);
    assert.equal(f.navigation.length,0,'do not leave the confirmation without a restorable receipt');
    assert.equal(f.session.getItem('ia4tube.edit.receipt.v1'),null);
    assert.equal([...f.session.values.keys()].filter(key=>key.startsWith('ia4tube.edit.pending.v1.')).length,1);
    const attempts=[...f.local.values.entries()].filter(([key])=>key.startsWith('ia4tube.edit.attempt.v2.'));
    assert.equal(attempts.length,1);
    assert.match(attempts[0][1],/^[a-f0-9-]{36}$/,'unretired attempt is retained, not marked confirmed');
    await f.submit();assert.equal(f.requests.length,1,'a late event still cannot submit from confirmation');
    f.session.setItem=setItem;f.reopen();const recovery=f.submit();await f.waitForRequest(2);
    assert.equal(f.requests[1].options.headers['Idempotency-Key'],original.options.headers['Idempotency-Key']);
    f.succeed(1,savedIds[0]);await recovery;
    assert.equal(JSON.parse(f.session.getItem('ia4tube.edit.receipt.v1')).orderId,savedIds[0]);
    assert.equal([...f.session.values.keys()].filter(key=>key.startsWith('ia4tube.edit.pending.v1.')).length,0);
  });
}

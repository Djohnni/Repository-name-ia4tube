class Element {
  constructor(tag='div') {
    this.tag=tag;this.children=[];this.listeners=new Map();this.selectors=new Map();
    this.attributes=new Map();this.value='';this.textContent='';this.innerHTML='';
    this.hidden=false;this.disabled=false;this.checked=false;this.files=[];this.dataset={};
  }
  append(...children) {this.children.push(...children);}
  before(element) {this.insertedBefore=element;}
  after(element) {this.insertedAfter=element;}
  replaceChildren() {this.children=[];this.value='';}
  addEventListener(type,handler) {this.listeners.set(type,handler);}
  async emit(type) {return this.listeners.get(type)?.({preventDefault(){}});}
  setAttribute(key,value) {this.attributes.set(key,value);}
  getAttribute(key) {return this.attributes.get(key)??null;}
  removeAttribute(key) {this.attributes.delete(key);delete this[key];}
  scrollIntoView() {}
  focus() {}
  select() {}
  closest(selector) {assert.equal(selector,'label');return this.label;}
  querySelector(selector) {
    if(this.selectors.has(selector))return this.selectors.get(selector);
    // Product cards are generated by products-form even in a single-product order.
    if(this.tag==='fieldset' && (/^\[data-field="[a-zA-Z]+"\]$/.test(selector)||selector==='[data-speech]')) {
      const field=new Element('input');this.selectors.set(selector,field);return field;
    }
    throw new Error('Unexpected selector: '+selector);
  }
  querySelectorAll(selector) {
    if(this.selectors.has(selector))return this.selectors.get(selector);
    throw new Error('Unexpected selector list: '+selector);
  }
}

